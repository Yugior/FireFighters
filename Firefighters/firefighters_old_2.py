class Tablero(Model):
    def __init__(self, width=8, height=6, num_agentes=6, tipo_agente=None, archivo_config=None):
        super().__init__()

        self.grid = MultiGrid(width, height, torus=False)
        self.schedule = []
        self.current_id = 0
        self.base_position = [(6,0),(0,3),(9,4),(3,7)]
        self.cells = np.zeros((width, height))  # Ya no usaremos esto para civiles
        self.paredes = {}
        self.puertas = {}
        self.paredes_dano = {}  # Nuevo: daño en paredes
        self.steps = 0
        self.civiles_rescatados = 0
        self.civiles_perdidos = 0
        self.puntos_dano = 0
        self.tipo_agente = tipo_agente

        # Sistema de POI (Puntos de Interés)
        self.posicionesPOI = set()  # POI visibles en el tablero (siempre 3)
        self.poi_sin_revelar = []   # Lista de (pos, tipo) donde tipo='v' o 'f'
        self.civiles_revelados = {}  # {pos: True} - civiles que ya fueron revelados
        self.falsas_alarmas_reveladas = set()  # posiciones de falsas alarmas reveladas

        # Estados del fuego/humo/daño
        self.posicionesFuego = set()
        self.posicionesHumo = set()
        self.posicionesDano = set()

        self.datacollector = DataCollector(
            model_reporters={
                "Civiles_rescatados": lambda m: m.civiles_rescatados,
                "Civiles_perdidos": lambda m: m.civiles_perdidos,
                "POI_activos": lambda m: len(m.posicionesPOI),
                "Puertas_abiertas": lambda m: sum(1 for p in m.puertas.values() if p.get('abierta')),
                "Steps": lambda m: m.steps,
                "Fuegos_Activos": lambda m: len(m.posicionesFuego),
                "Humo_Activos": lambda m: len(m.posicionesHumo),
                "Puntos_Dano": lambda m: m.puntos_dano
            },
            agent_reporters={
                "Civiles": lambda a: a.civilesRes,
                "Visitadas": lambda a: a.visited,
                "Fuegos_Apagados": lambda a: a.apagarFuego,
            }
        )

        if archivo_config:
            self.cargar_configuracion(archivo_config)
        else:
            self.configuracion_default()

        # Colocar 3 POI iniciales
        self.colocar_poi_iniciales()

        for i in range(num_agentes):
            self.agregar_bombero()

        self.datacollector.collect(self)

    def agregar_bombero(self):
        """Agrega un bombero en posición válida"""
        intentos = 0
        max_intentos = 100

        while intentos < max_intentos:
            x = self.random.randrange(self.grid.width)
            y = self.random.randrange(self.grid.height)

            if (self.grid.is_cell_empty((x, y)) and
                (x, y) not in self.base_position and # Changed to 'not in'
                (x, y) not in self.posicionesPOI and
                (x, y) not in self.posicionesFuego):

                try:
                    bombero = self.tipo_agente(self)
                    self.grid.place_agent(bombero, (x, y))
                    self.schedule.append(bombero)
                    return True
                except Exception as e:
                    print(f"Error al agregar bombero en ({x},{y}): {e}")
                    pass

            intentos += 1

        print(f"Advertencia: No se pudo colocar bombero después de {max_intentos} intentos")
        return False

    def cargar_configuracion(self, archivo):
        with open(archivo, 'r') as f:
            lines = [line.strip() for line in f.readlines() if line.strip()]

        idx = 0

        # 1. Cargar paredes (6 líneas)
        for row in range(6):
            if idx >= len(lines):
                break
            line_parts = lines[idx].split()
            for col in range(min(8, len(line_parts))):
                wall_config = line_parts[col]
                if len(wall_config) == 4:
                    self.paredes[(col, row)] = {
                        'arriba': wall_config[0] == '1',
                        'derecha': wall_config[1] == '1',
                        'abajo': wall_config[2] == '1',
                        'izquierda': wall_config[3] == '1'
                    }
                    # Inicializar daño en paredes
                    self.paredes_dano[(col, row)] = {
                        'arriba': 0, 'izquierda': 0, 'abajo': 0, 'derecha': 0
                    }
            idx += 1

        # 2. Cargar POI (3 líneas iniciales, pero crearemos pool de 15)
        poi_iniciales = []
        for _ in range(3):
            if idx >= len(lines):
                break
            parts = lines[idx].split()
            if len(parts) >= 3:
                row = int(parts[0]) - 1
                col = int(parts[1]) - 1
                tipo = parts[2]  # 'v' o 'f'
                if 0 <= row < 6 and 0 <= col < 8:
                    poi_iniciales.append(((col, row), tipo))
            idx += 1

        # Crear pool de 15 POI (10 civiles, 5 falsas alarmas)
        # Los primeros 3 del archivo + 12 aleatorios
        self.poi_sin_revelar = poi_iniciales.copy()

        # Generar 12 POI adicionales aleatorios
        civiles_necesarios = 10 - sum(1 for _, tipo in poi_iniciales if tipo == 'v')
        falsas_necesarias = 5 - sum(1 for _, tipo in poi_iniciales if tipo == 'f')

        posiciones_ocupadas = {pos for pos, _ in poi_iniciales}
        for pos in self.base_position: # Changed to iterate through base_position
            posiciones_ocupadas.add(pos)

        # Generar civiles
        for _ in range(civiles_necesarios):
            while True:
                x = self.random.randrange(self.grid.width)
                y = self.random.randrange(self.grid.height)
                if (x, y) not in posiciones_ocupadas:
                    self.poi_sin_revelar.append(((x, y), 'v'))
                    posiciones_ocupadas.add((x, y))
                    break

        # Generar falsas alarmas
        for _ in range(falsas_necesarias):
            while True:
                x = self.random.randrange(self.grid.width)
                y = self.random.randrange(self.grid.height)
                if (x, y) not in posiciones_ocupadas:
                    self.poi_sin_revelar.append(((x, y), 'f'))
                    posiciones_ocupadas.add((x, y))
                    break

        # Mezclar el pool
        self.random.shuffle(self.poi_sin_revelar)

        # 3. Cargar posiciones iniciales de fuego (10 líneas)
        for _ in range(10):
            if idx >= len(lines):
                break
            parts = lines[idx].split()
            if len(parts) >= 2:
                row = int(parts[0]) - 1
                col = int(parts[1]) - 1
                if 0 <= row < 6 and 0 <= col < 8:
                    self.posicionesFuego.add((col, row))
            idx += 1

        # 4. Cargar puertas (8 líneas)
        for _ in range(8):
            if idx >= len(lines):
                break
            parts = lines[idx].split()
            if len(parts) >= 4:
                r1 = int(parts[0]) - 1
                c1 = int(parts[1]) - 1
                r2 = int(parts[2]) - 1
                c2 = int(parts[3]) - 1
                if (0 <= r1 < 6 and 0 <= c1 < 8 and 0 <= r2 < 6 and 0 <= c2 < 8):
                    celda1 = (c1, r1)
                    celda2 = (c2, r2)
                    key = tuple(sorted([celda1, celda2]))
                    self.puertas[key] = {'abierta': False}
            idx += 1

    def colocar_poi_iniciales(self):
        """Coloca 3 POI en el tablero desde el pool"""
        for _ in range(min(3, len(self.poi_sin_revelar))):
            if self.poi_sin_revelar:
                pos, tipo = self.poi_sin_revelar.pop(0)
                # Si hay fuego en esa posición, no colocar ahí
                if pos not in self.posicionesFuego:
                    self.posicionesPOI.add(pos)
                    # Guardar el tipo para cuando se revele
                    if tipo == 'v':
                        self.civiles_revelados[pos] = False  # No revelado aún
                    # Las falsas alarmas no necesitan tracking especial

    def generar_nuevo_poi(self):
        """Genera un nuevo POI en posición válida"""
        if not self.poi_sin_revelar:
            return  # No hay más POI disponibles

        intentos = 0
        while intentos < 50 and self.poi_sin_revelar:
            pos, tipo = self.poi_sin_revelar.pop(0)

            # Verificar que no haya fuego
            if pos not in self.posicionesFuego and pos not in self.posicionesPOI:
                self.posicionesPOI.add(pos)
                if tipo == 'v':
                    self.civiles_revelados[pos] = False
                return
            else:
                # Si había fuego, generar otro
                intentos += 1

        # Si no pudimos colocar, poner en posición aleatoria válida
        if self.poi_sin_revelar:
            pos, tipo = self.poi_sin_revelar.pop(0)
            intentos = 0
            while intentos < 100:
                x = self.random.randrange(self.grid.width)
                y = self.random.randrange(self.grid.height)
                if ((x, y) not in self.posicionesFuego and
                    (x, y) not in self.posicionesPOI and
                    (x, y) not in self.base_position): # Changed to 'not in'
                    self.posicionesPOI.add((x, y))
                    if tipo == 'v':
                        self.civiles_revelados[(x, y)] = False
                    return
                intentos += 1

    def configuracion_default(self):
        for x in range(self.grid.width):
            for y in range(self.grid.height):
                self.paredes[(x, y)] = {
                    'arriba': y == 0,
                    'abajo': y == self.grid.height - 1,
                    'izquierda': x == 0,
                    'derecha': x == self.grid.width - 1
                }
                self.paredes_dano[(x, y)] = {
                    'arriba': 0, 'izquierda': 0, 'abajo': 0, 'derecha': 0
                }

    def hay_pared_entre(self, celda1, celda2):
        """Verifica si hay pared entre dos celdas (considerando daño)"""
        x1, y1 = celda1
        x2, y2 = celda2

        if abs(x1 - x2) + abs(y1 - y2) != 1:
            return False

        direccion = None
        if x2 > x1:
            direccion = 'derecha'
        elif x2 < x1:
            direccion = 'izquierda'
        elif y2 > y1:
            direccion = 'abajo'
        elif y2 < y1:
            direccion = 'arriba'

        # Si la pared tiene 2+ de daño, está destruida
        if self.paredes_dano.get(celda1, {}).get(direccion, 0) >= 2:
            return False

        return self.paredes.get(celda1, {}).get(direccion, False)

    def hay_puerta_entre(self, celda1, celda2):
        key = tuple(sorted([celda1, celda2]))
        return key in self.puertas

    def esta_puerta_abierta(self, celda1, celda2):
        key = tuple(sorted([celda1, celda2]))
        return self.puertas.get(key, {}).get('abierta', False)

    def is_poi(self, pos):
        """Verifica si hay un POI en esta posición"""
        return pos in self.posicionesPOI

    def revelar_poi(self, pos):
        """Revela un POI: puede ser civil o falsa alarma"""
        if pos not in self.posicionesPOI:
            return None

        # Determinar si es civil o falsa alarma
        if pos in self.civiles_revelados:
            # Es un civil
            self.civiles_revelados[pos] = True  # Marcar como revelado
            return 'civil'
        else:
            # Es falsa alarma
            self.falsas_alarmas_reveladas.add(pos)
            self.posicionesPOI.remove(pos)
            # Generar nuevo POI
            if len(self.posicionesPOI) < 3:
                self.generar_nuevo_poi()
            return 'falsa_alarma'

    def quitar_civil(self, pos):
        """Marca un civil como recogido por un bombero (solo si está revelado)"""
        if pos in self.civiles_revelados and self.civiles_revelados[pos]:
            del self.civiles_revelados[pos]
            self.posicionesPOI.discard(pos)
            # The increment of civiles_rescatados is now handled in Bombero.step
            # Generar nuevo POI
            if len(self.posicionesPOI) < 3:
                self.generar_nuevo_poi()
            return True
        return False

    def is_all_collected(self):
        """Victoria: 7 civiles rescatados"""
        return self.civiles_rescatados >= 7

    def all_agents_empty(self):
        return all(not a.tieneCivil for a in self.schedule)

    def verificar_game_over(self):
        """Verifica condiciones de derrota"""
        if self.civiles_perdidos >= 4:
            return True, "4 civiles heridos"
        if self.puntos_dano >= 25:
            return True, "Edificio colapsado"
        return False, None

    # ========== MÉTODOS DE FUEGO ==========

    def tieneFuegoEn(self, pos):
        return pos in self.posicionesFuego

    def tieneHumoEn(self, pos):
        return pos in self.posicionesHumo

    def tieneDanoEn(self, pos):
        return pos in self.posicionesDano

    def obtenerPosicionesFuego(self):
        return list(self.posicionesFuego)

    def esPosicionValida(self, pos):
        x, y = pos
        return 0 <= x < self.grid.width and 0 <= y < self.grid.height

    def puedePropagar(self, origen, destino):
        """Determina si el fuego/humo puede propagarse entre dos celdas"""
        x1, y1 = origen
        x2, y2 = destino

        if not (0 <= x2 < self.grid.width and 0 <= y2 < self.grid.height):
            return False

        if x2 == x1 and y2 == y1 - 1:
            dir_origen, dir_destino = 'arriba', 'abajo'
        elif x2 == x1 and y2 == y1 + 1:
            dir_origen, dir_destino = 'abajo', 'arriba'
        elif y2 == y1 and x2 == x1 - 1:
            dir_origen, dir_destino = 'izquierda', 'derecha'
        elif y2 == y1 and x2 == x1 + 1:
            dir_origen, dir_destino = 'derecha', 'izquierda'
        else:
            return False

        # Si pared tiene 2+ daño, está destruida
        if self.paredes_dano.get((x1, y1), {}).get(dir_origen, 0) >= 2:
            return True

        # Si hay pared intacta, no se propaga
        if self.paredes.get((x1, y1), {}).get(dir_origen, False):
            return False
        if self.paredes.get((x2, y2), {}).get(dir_destino, False):
            return False

        # Si hay puerta
        clave = tuple(sorted([origen, destino]))
        if clave in self.puertas:
            return self.puertas[clave]['abierta']

        return True

    def propagarFuego(self):
        """Propaga fuego con probabilidad del 10%"""
        nuevosFuegos = set()

        for posFuego in list(self.posicionesFuego):
            x, y = posFuego
            adyacentes = [(x-1,y), (x+1,y), (x,y-1), (x,y+1)]

            for adjPos in adyacentes:
                if (self.puedePropagar(posFuego, adjPos) and
                    not self.tieneFuegoEn(adjPos) and
                    self.random.random() < 0.10):
                    nuevosFuegos.add(adjPos)

        self.posicionesFuego.update(nuevosFuegos)

        # Verificar si fuego revela/hiere POIs
        for pos in nuevosFuegos:
            if pos in self.posicionesPOI:
                if pos in self.civiles_revelados:
                    # Civil herido
                    self.civiles_perdidos += 1
                    del self.civiles_revelados[pos]
                    self.posicionesPOI.remove(pos)
                    if len(self.posicionesPOI) < 3:
                        self.generar_nuevo_poi()
                else:
                    # Falsa alarma quemada
                    self.posicionesPOI.remove(pos)
                    if len(self.posicionesPOI) < 3:
                        self.generar_nuevo_poi()

    def quitarFuego(self, pos):
        if pos in self.posicionesFuego:
            self.posicionesFuego.remove(pos)

    def generarHumo(self):
        """Genera humo en celdas adyacentes a fuego"""
        for posFuego in list(self.posicionesFuego):
            x, y = posFuego
            adyacentes = [(x-1,y), (x+1,y), (x,y-1), (x,y+1)]

            for adjPos in adyacentes:
                if (self.esPosicionValida(adjPos) and
                    not self.tieneFuegoEn(adjPos)):
                    self.posicionesHumo.add(adjPos)

    def quitarHumo(self, pos):
        if pos in self.posicionesHumo:
            self.posicionesHumo.remove(pos)

    def verificarExplosiones(self):
        """Si una celda tiene >= 4 celdas de fuego adyacentes, explota"""
        for pos in list(self.posicionesFuego):
            x, y = pos
            fuegosAdyacentes = 0
            adyacentes = [(x-1,y), (x+1,y), (x,y-1), (x,y+1)]

            for adjPos in adyacentes:
                if self.tieneFuegoEn(adjPos):
                    fuegosAdyacentes += 1

            if fuegosAdyacentes >= 4:
                self.explosion(pos)

    def explosion(self, pos):
        """Causa daño y elimina el fuego en la celda"""
        x, y = pos
        self.puntos_dano += 2
        self.posicionesDano.add(pos)
        self.posicionesFuego.discard(pos)

        # Propagar daño con probabilidad 0.2
        adyacentes = [(x-1,y), (x+1,y), (x,y-1), (x,y+1)]
        for adjPos in adyacentes:
            if self.esPosicionValida(adjPos):
                if self.random.random() < 0.2:
                    self.posicionesDano.add(adjPos)
                    # Dañar paredes adyacentes
                    self.danar_pared_entre(pos, adjPos)

    def danar_pared_entre(self, pos1, pos2):
        """Aplica 1 punto de daño a la pared entre dos celdas"""
        x1, y1 = pos1
        x2, y2 = pos2

        if x2 > x1:
            self.paredes_dano[(x1, y1)]['derecha'] += 1
        elif x2 < x1:
            self.paredes_dano[(x1, y1)]['izquierda'] += 1
        elif y2 > y1:
            self.paredes_dano[(x1, y1)]['abajo'] += 1
        elif y2 < y1:
            self.paredes_dano[(x1, y1)]['arriba'] += 1

    def aplicarDano(self):
        """Daño aleatorio por fuego"""
        for pos in list(self.posicionesFuego):
            if self.random.random() < 0.05:
                self.puntos_dano += 1
                self.posicionesDano.add(pos)

    def generar_fuego(self):
        """Función principal de generación de fuego"""
        self.propagarFuego()
        self.generarHumo()
        self.verificarExplosiones()
        self.aplicarDano()

    def step(self):
        """Ejecuta un paso de la simulación"""
        for agent in list(self.schedule):
            agent.step()
            self.generar_fuego()

        self.datacollector.collect(self)
        self.steps += 1

def get_grid(model):
    """
    Genera una matriz numérica basada en el estado del modelo.

    Códigos:
    0 = vacío
    1 = POI (punto de interés sin revelar)
    2 = bombero
    3 = base
    4 = humo
    5 = fuego
    6 = civil revelado
    """
    grid = np.zeros((model.grid.width, model.grid.height))

    for content, (x, y) in model.grid.coord_iter():
        # Orden de prioridad
        if (x, y) in model.posicionesFuego:
            grid[x][y] = 5  # Fuego
        elif (x, y) in model.posicionesHumo:
            grid[x][y] = 4  # Humo
        elif (x, y) in model.base_position: # Changed to 'in'
            grid[x][y] = 3  # Base
        elif (x, y) in model.civiles_revelados and model.civiles_revelados[(x, y)]:
            grid[x][y] = 6  # Civil revelado
        elif (x, y) in model.posicionesPOI:
            grid[x][y] = 1  # POI sin revelar
        elif content:  # Hay un bombero
            grid[x][y] = 2  # Bombero
        else:
            grid[x][y] = 0  # Vacío

    return grid


