class Bombero(Agent):
    def __init__(self, model, energia_maxima=4):
        super().__init__(model)

        self.visited = 0
        self.apagarFuego = 0
        self.apagarHumo = 0
        self.civilesRes = 0
        self.puertas_abiertas = 0
        self.energia_maxima = energia_maxima
        self.energia_actual = energia_maxima
        self.energia_guardada = 0
        self.tieneCivil = False
        self.celdas_exploradas = set()
        self.ultimo_objetivo = None

    def puede_moverse(self, desde, hacia):
        if not self.model.hay_pared_entre(desde, hacia):
            return True
        if self.model.hay_puerta_entre(desde, hacia):
            return self.model.esta_puerta_abierta(desde, hacia)
        return False

    def abrir_puerta(self, desde, hacia):
        if self.energia_actual < 1:
            return False
        if self.model.hay_puerta_entre(desde, hacia):
            if not self.model.esta_puerta_abierta(desde, hacia):
                key = tuple(sorted([desde, hacia]))
                self.model.puertas[key]['abierta'] = True
                self.energia_actual -= 1
                self.puertas_abiertas += 1
                return True
        return False

    def apagar_fuego(self):
        """Apaga el fuego en la celda actual (cuesta 1 energía)"""
        if self.energia_actual < 1:
            return False
        if self.model.tieneFuegoEn(self.pos):
            self.model.quitarFuego(self.pos)
            self.energia_actual -= 1
            self.apagarFuego += 1
            return True
        return False

    def apagar_humo(self):
        """Apaga el humo en la celda actual (cuesta 1 energía)"""
        if self.energia_actual < 1:
            return False
        if self.model.tieneHumoEn(self.pos):
            self.model.quitarHumo(self.pos)
            self.energia_actual -= 1
            self.apagarHumo += 1
            return True
        return False

    def gastar_energia(self, cantidad=1):
        if self.energia_actual >= cantidad:
            self.energia_actual -= cantidad
            return True
        return False

    def get_neighbors(self):
        return self.model.grid.get_neighborhood(
            self.pos, moore=False, include_center=False
        )

    def buscar_camino_bfs(self, objetivo):
        if self.pos == objetivo:
            return []
        visitados = {self.pos}
        cola = deque([(self.pos, [])])

        while cola:
            actual, camino = cola.popleft()
            vecinos = self.model.grid.get_neighborhood(
                actual, moore=False, include_center=False
            )
            for vecino in vecinos:
                if vecino not in visitados:
                    puede_pasar = self.puede_moverse(actual, vecino)
                    hay_puerta = self.model.hay_puerta_entre(actual, vecino)
                    if puede_pasar or hay_puerta:
                        nuevo_camino = camino + [vecino]
                        if vecino == objetivo:
                            return nuevo_camino
                        visitados.add(vecino)
                        cola.append((vecino, nuevo_camino))
        return None

    def encontrar_poi_mas_cercano(self):
        """Encuentra el POI (punto de interés) más cercano"""
        pois = []
        for pos in self.model.posicionesPOI:
            camino = self.buscar_camino_bfs(pos)
            if camino is not None:
                pois.append((pos, len(camino)))
        if not pois:
            return None
        poi_cercano = min(pois, key=lambda x: x[1])
        return poi_cercano[0]

    def encontrar_civil_revelado_mas_cercano(self):
        """Encuentra el civil ya revelado más cercano"""
        civiles = []
        for pos, revelado in self.model.civiles_revelados.items():
            if revelado:  # Solo civiles revelados
                camino = self.buscar_camino_bfs(pos)
                if camino is not None:
                    civiles.append((pos, len(camino)))
        if not civiles:
            return None
        return min(civiles, key=lambda x: x[1])[0]

    def encontrar_fuego_mas_cercano(self):
        """Encuentra el fuego más cercano"""
        fuegos = []
        for pos in self.model.posicionesFuego:
            camino = self.buscar_camino_bfs(pos)
            if camino is not None:
                fuegos.append((pos, len(camino)))
        if not fuegos:
            return None
        return min(fuegos, key=lambda x: x[1])[0]

    def mover_hacia(self, objetivo):
        if self.energia_actual < 1:
            return False
        camino = self.buscar_camino_bfs(objetivo)
        if not camino:
            return False
        siguiente = camino[0]

        if self.puede_moverse(self.pos, siguiente):
            self.model.grid.move_agent(self, siguiente)
            self.visited += 1
            self.energia_actual -= 1
            self.celdas_exploradas.add(siguiente)

            # Verificar si llegó a un POI
            if self.model.is_poi(siguiente):
                tipo = self.model.revelar_poi(siguiente)
                if tipo == 'civil':
                    # Recoger civil
                    self.model.quitar_civil(siguiente)
                    self.civilesRes += 1
                    self.tieneCivil = True
                # Si es falsa alarma, no hace nada (ya se removió del tablero)
            return True

        elif self.model.hay_puerta_entre(self.pos, siguiente):
            if not self.model.esta_puerta_abierta(self.pos, siguiente):
                return self.abrir_puerta(self.pos, siguiente)
        return False

    def base_mas_cercana(self):
      """Retorna la base más cercana según BFS."""
      mejores = []

      for base in self.model.base_position:
          camino = self.buscar_camino_bfs(base)
          if camino is not None:
              mejores.append((base, len(camino)))

      if not mejores:
          return None

      base_cercana = min(mejores, key=lambda x: x[1])
      return base_cercana[0]

    def movimiento_aleatorio(self):
        if self.energia_actual < 1:
            return False
        vecinos = list(self.get_neighbors())
        if not vecinos:
            return self.gastar_energia()
        np.random.shuffle(vecinos)

        for vecino in vecinos:
            if self.puede_moverse(self.pos, vecino):
                self.model.grid.move_agent(self, vecino)
                self.visited += 1
                self.energia_actual -= 1

                # Verificar si llegó a un POI
                if self.model.is_poi(vecino):
                    tipo = self.model.revelar_poi(vecino)
                    if tipo == 'civil':
                        self.model.quitar_civil(vecino)
                        self.civilesRes += 1
                        self.tieneCivil = True
                return True

        for vecino in vecinos:
            if self.model.hay_puerta_entre(self.pos, vecino):
                if not self.model.esta_puerta_abierta(self.pos, vecino):
                    return self.abrir_puerta(self.pos, vecino)

        return self.gastar_energia()

    def step(self):
        self.energia_actual = self.energia_maxima + self.energia_guardada
        self.energia_guardada = 0
        self.celdas_exploradas.add(self.pos)

        if self.pos in self.model.base_position and self.tieneCivil:
            self.tieneCivil = False
            self.model.civiles_rescatados += 1 # Increment only on delivery

        while self.energia_actual > 0:
            accion_realizada = False

            # PRIORIDAD 1: Apagar fuego en posición actual
            if self.model.tieneFuegoEn(self.pos):
                accion_realizada = self.apagar_fuego()
                if accion_realizada:
                    continue

            # PRIORIDAD 2: Apagar humo en posición actual
            if self.model.tieneHumoEn(self.pos):
                accion_realizada = self.apagar_humo()
                if accion_realizada:
                    continue

            # PRIORIDAD 3: Si tiene civil, ir a la base
            if self.tieneCivil:
                base = self.base_mas_cercana()
                if base is not None and self.pos != base:
                    accion_realizada = self.mover_hacia(base)
                else:
                    accion_realizada = self.gastar_energia()
            else:
                # PRIORIDAD 4: Buscar civil revelado
                civil_objetivo = self.encontrar_civil_revelado_mas_cercano()
                if civil_objetivo:
                    accion_realizada = self.mover_hacia(civil_objetivo)
                else:
                    # PRIORIDAD 5: Buscar POI no revelado
                    poi_objetivo = self.encontrar_poi_mas_cercano()
                    if poi_objetivo:
                        accion_realizada = self.mover_hacia(poi_objetivo)
                    else:
                        # PRIORIDAD 6: Combatir fuego
                        fuego_objetivo = self.encontrar_fuego_mas_cercano()
                        if fuego_objetivo:
                            accion_realizada = self.mover_hacia(fuego_objetivo)
                        else:
                            accion_realizada = self.movimiento_aleatorio()

            if not accion_realizada:
                self.gastar_energia()

        if self.energia_actual > 0:
            self.energia_guardada = min(self.energia_actual, self.energia_maxima)


class BomberoAleatorio(Bombero):
    def step(self):
        self.energia_actual = self.energia_maxima + self.energia_guardada
        self.energia_guardada = 0

        if self.pos in self.model.base_position and self.tieneCivil:
            self.tieneCivil = False
            self.model.civiles_rescatados += 1 # Increment only on delivery

        while self.energia_actual > 0:
            # Usar np.random para probabilidades
            accion = np.random.choice(['mover', 'puerta', 'fuego', 'humo', 'nada'],
                                     p=[0.5, 0.15, 0.15, 0.1, 0.1])

            if accion == 'mover':
                self.movimiento_aleatorio()
            elif accion == 'puerta':
                vecinos = list(self.get_neighbors())
                if vecinos:
                    vecino = vecinos[np.random.randint(len(vecinos))]
                    if self.model.hay_puerta_entre(self.pos, vecino):
                        self.abrir_puerta(self.pos, vecino)
                    else:
                        self.gastar_energia()
                else:
                    self.gastar_energia()
            elif accion == 'fuego':
                if not self.apagar_fuego():
                    self.gastar_energia()
            elif accion == 'humo':
                if not self.apagar_humo():
                    self.gastar_energia()
            else:
                self.gastar_energia()

        if self.energia_actual > 0:
            self.energia_guardada = min(self.energia_actual, self.energia_maxima)

def get_grid(model):
    """
    Genera una matriz numérica basada en el estado del modelo.

    Códigos:
    0 = vacío
    1 = POI (punto de interés sin revelar)
    2 = bombero
    3 = base
    4 = humo
    5 = fuego
    6 = civil revelado
    """
    grid = np.zeros((model.grid.width, model.grid.height))

    for content, (x, y) in model.grid.coord_iter():
        # Orden de prioridad
        if (x, y) in model.posicionesFuego:
            grid[x][y] = 5  # Fuego
        elif (x, y) in model.posicionesHumo:
            grid[x][y] = 4  # Humo
        elif (x, y) in model.base_position:
            grid[x][y] = 3  # Base
        elif (x, y) in model.civiles_revelados and model.civiles_revelados[(x, y)]:
            grid[x][y] = 6  # Civil revelado
        elif (x, y) in model.posicionesPOI:
            grid[x][y] = 1  # POI sin revelar
        elif content:  # Hay un bombero
            grid[x][y] = 2  # Bombero
        else:
            grid[x][y] = 0  # Vacío

    return grid

