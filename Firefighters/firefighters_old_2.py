def ejecutar_simulacion_accion_por_accion(tipo_agente, max_steps=50, archivo_config='config.txt',
                                          max_frames=5000, verbose=True):
    """
    Ejecuta simulación guardando UN frame por cada ACCIÓN de agente.
    - Reproduce la lógica de acción que usan tus agentes (movimiento/puerta/nada).
    - Genera fuego justo después de cada acción (regla estricta).
    - max_frames: límite protector para evitar memory blowup.
    """
    model = Tablero(width=8, height=6, num_agentes=6,
                   tipo_agente=tipo_agente, archivo_config=archivo_config)

    history_models = []
    history_models.append(copy.deepcopy(model))

    frames = 1
    if verbose:
        print("Iniciando simulación acción-por-acción...")
        print(f"Agentes: {len(model.schedule)} - Civiles: {np.sum(model.cells==3)} - Fuegos: {len(model.posicionesFuego)}")

    for step in range(max_steps):
        if verbose and (step % 5 == 0):
            print(f" Step {step} ... frames guardados: {frames}")

        # Recorremos cada agente y ejecutamos sus acciones una a una
        for agent_idx, agent in enumerate(list(model.schedule)):
            # Preparar al agente (igual que en tu detallada)
            # recargar energía inicial del turno
            agent.energia_actual = agent.energia_maxima + agent.energia_guardada
            agent.energia_guardada = 0

            # Si tiene civil y está en base, entregar inmediatamente (y guardar estado)
            if hasattr(agent, "tieneCivil") and agent.tieneCivil and agent.pos == model.base_position:
                agent.tieneCivil = False
                history_models.append(copy.deepcopy(model))
                frames += 1
                if frames >= max_frames:
                    if verbose: print("Máximo de frames alcanzado, abortando.")
                    return history_models

            # Ejecutar acciones una por una hasta que se agote energía
            while getattr(agent, "energia_actual", 0) > 0:
                # Guardar estado anterior para detectar cambios (opcional)
                pos_antes = getattr(agent, "pos", None)
                energia_antes = getattr(agent, "energia_actual", None)
                civil_antes = getattr(agent, "tieneCivil", None)

                # --- lógica para bombero aleatorio vs inteligente ---
                if isinstance(agent, BomberoAleatorio):
                    accion = np.random.choice(['mover', 'puerta', 'nada'], p=[0.7, 0.2, 0.1])

                    if accion == 'mover':
                        agent.movimiento_aleatorio()
                    elif accion == 'puerta':
                        vecinos = list(agent.get_neighbors())
                        if vecinos:
                            idx = np.random.choice(len(vecinos))
                            vecino = vecinos[idx]
                            if model.hay_puerta_entre(agent.pos, vecino):
                                agent.abrir_puerta(agent.pos, vecino)
                            else:
                                agent.gastar_energia()
                        else:
                            agent.gastar_energia()
                    else:
                        agent.gastar_energia()

                else:
                    # Bombero "inteligente" (usa tus métodos existentes)
                    accion_realizada = False

                    if getattr(agent, "tieneCivil", False):
                        if agent.pos != model.base_position:
                            accion_realizada = agent.mover_hacia(model.base_position)
                        else:
                            accion_realizada = agent.gastar_energia()
                    else:
                        civil_objetivo = agent.encontrar_civil_mas_cercano()
                        if civil_objetivo:
                            accion_realizada = agent.mover_hacia(civil_objetivo)
                        else:
                            accion_realizada = agent.movimiento_aleatorio()

                    if not accion_realizada:
                        agent.gastar_energia()

                # --- Después de CADA acción: generar fuego (regla) y guardar frame ---
                model.generar_fuego()

                history_models.append(copy.deepcopy(model))
                frames += 1

                # Límite de seguridad en frames
                if frames >= max_frames:
                    if verbose: print("Máximo de frames alcanzado, abortando.")
                    return history_models

                # Si se rescata un civil y llega a base, se habrá registrado en state
                # Nota: no incrementamos model.steps aquí; se hace después de ciclo completo

        # Fin de turno (todos los agentes actuaron una vez)
        model.steps += 1
        model.datacollector.collect(model)

        # Comprobaciones de fin
        game_over, razon = (False, None)
        if hasattr(model, "verificar_game_over"):
            game_over, razon = model.verificar_game_over()
        if game_over:
            if verbose: print(f"Game over en step {step}: {razon}")
            break
        if model.is_all_collected():
            if verbose: print(f"Todos los civiles rescatados en step {step}")
            break

    if verbose:
        print("Simulación acción-por-acción completada.")
        print(f"Frames guardados: {len(history_models)} - Steps ejecutados: {model.steps}")

    return history_models


