    def puedePropagar(self, origen, destino):
        """Determina si el fuego/humo puede propagarse entre dos celdas"""
        x1, y1 = origen
        x2, y2 = destino

        if not (0 <= x2 < self.grid.width and 0 <= y2 < self.grid.height):
            return False

        if x2 == x1 and y2 == y1 - 1:
            dir_origen, dir_destino = 'arriba', 'abajo'
        elif x2 == x1 and y2 == y1 + 1:
            dir_origen, dir_destino = 'abajo', 'arriba'
        elif y2 == y1 and x2 == x1 - 1:
            dir_origen, dir_destino = 'izquierda', 'derecha'
        elif y2 == y1 and x2 == x1 + 1:
            dir_origen, dir_destino = 'derecha', 'izquierda'
        else:
            return False

        # Si pared tiene 2+ daño, está destruida
        if self.paredes_dano[(x1, y1)].get(dir_origen, 0) >= 2:
            return True

        # Si hay pared intacta, no se propaga
        if self.paredes[(x1, y1)].get(dir_origen, False):
            return False
        if self.paredes[(x2, y2)].get(dir_destino, False):
            return False

        # Si hay puerta
        clave = tuple(sorted([origen, destino]))
        if clave in self.puertas:
            return self.puertas[clave]['abierta']

        return True

    def propagarFuego(self):
        """Propaga fuego con probabilidad del 10%.
        Además: si hay HUMO adyacente a un fuego, el HUMO se convierte en FUEGO inmediatamente.
        """
        nuevosFuegos = set()

        for posFuego in list(self.posicionesFuego):
            x, y = posFuego
            adyacentes = [(x-1,y), (x+1,y), (x,y-1), (x,y+1)]

            for adjPos in adyacentes:
                if not self.esPosicionValida(adjPos):
                    continue

                # Si hay HUMO al lado del fuego → se convierte en fuego inmediatamente
                if adjPos in self.posicionesHumo and self.puedePropagar(posFuego, adjPos):
                    self.posicionesHumo.discard(adjPos)
                    nuevosFuegos.add(adjPos)
                    continue

                # Propagación normal con probabilidad 10% a celdas sin fuego
                if (self.puedePropagar(posFuego, adjPos) and
                    not self.tieneFuegoEn(adjPos) and
                    self.random.random() < 0.10):
                    nuevosFuegos.add(adjPos)

        self.posicionesFuego.update(nuevosFuegos)

        # Verificar si fuego revela/hiere POIs
        for pos in nuevosFuegos:
            if pos in self.posicionesPOI:
                if pos in self.civiles_revelados:
                    # Civil herido
                    self.civiles_perdidos += 1
                    del self.civiles_revelados[pos]
                    self.posicionesPOI.remove(pos)
                    if len(self.posicionesPOI) < 3:
                        self.generar_nuevo_poi()
                else:
                    # Falsa alarma quemada
                    self.posicionesPOI.remove(pos)
                    if len(self.posicionesPOI) < 3:
                        self.generar_nuevo_poi()

    def quitarFuego(self, pos):
        if pos in self.posicionesFuego:
            self.posicionesFuego.remove(pos)

    def generar_humo_aleatorio(self):
        """
        Genera HUMO de forma ALEATORIA en UNA celda por turno
        Reglas:
        - vacío/bombero → humo
        - humo → fuego (revela POI si aplica, daña bomberos)
        - fuego → explosión

        MODIFICADO: Si hay bombero, respawnea en base en lugar de quedar herido
        """
        # Seleccionar UNA celda aleatoria del tablero
        x = self.random.randrange(self.grid.width)
        y = self.random.randrange(self.grid.height)
        pos = (x, y)

        # Aplicar reglas de propagación
        if pos in self.posicionesFuego:
            # Si hay fuego → EXPLOSIÓN
            self.explosion(pos)

        elif pos in self.posicionesHumo:
            # Si hay humo → se convierte en FUEGO
            self.posicionesHumo.discard(pos)
            self.posicionesFuego.add(pos)

            # Verificar si hay bomberos en esta posición
            agents_in_cell = self.grid.get_cell_list_contents([pos])
            for agent in agents_in_cell:
                # Verificar si es un bombero (cualquier subclase)
                if hasattr(agent, 'herido'):
                    # MODIFICADO: En lugar de marcar como herido, respawnear en base
                    agent.respawnear_en_base()

            # Si el fuego revela un POI
            if pos in self.posicionesPOI:
                if pos in self.civiles_revelados:
                    # Civil herido
                    self.civiles_perdidos += 1
                    del self.civiles_revelados[pos]
                    self.posicionesPOI.remove(pos)
                    if len(self.posicionesPOI) < 3:
                        self.generar_nuevo_poi()
                else:
                    # Falsa alarma quemada
                    self.posicionesPOI.remove(pos)
                    if len(self.posicionesPOI) < 3:
                        self.generar_nuevo_poi()
        else:
            # Si está vacío (puede haber bombero) → generar HUMO
            self.posicionesHumo.add(pos)

