def ejecutar_simulacion_detallada(tipo_agente, max_steps=30, archivo_config='config.txt',
                                   frames_por_agente=False):
    """
    Ejecuta simulación con control de frames
    Si frames_por_agente=True, guarda frame por movimiento (muchos frames)
    Si frames_por_agente=False, guarda frame por step (menos frames)
    """
    model = Tablero(width=8, height=6, num_agentes=6,
                   tipo_agente=tipo_agente, archivo_config=archivo_config)

    history_models = []
    history_models.append(copy.deepcopy(model))

    print(f"Ejecutando simulación detallada...")
    print(f"Agentes: {len(model.schedule)}")
    print(f"Civiles iniciales: {np.sum(model.cells == 3)}")

    for step in range(max_steps):
        if step % 5 == 0:
            print(f"  Step {step}...")

        if frames_por_agente:
            # Guardar frame por cada agente
            for agent in model.schedule:
                agent.step()
                model.generar_fuego()
                history_models.append(copy.deepcopy(model))
            model.steps += 1
            model.datacollector.collect(model)
        else:
            # Guardar solo un frame por step completo
            model.step()
            history_models.append(copy.deepcopy(model))

        # Verificar condiciones de término
        game_over, razon = model.verificar_game_over()
        if game_over or model.is_all_collected():
            print(f"  Terminó en step {step}")
            break

    print(f"\nSimulación completada:")
    print(f"  Frames totales: {len(history_models)}")
    print(f"  Steps ejecutados: {model.steps}")
    print(f"  Civiles rescatados: {model.civiles_rescatados}")
    print(f"  Civiles perdidos: {model.civiles_perdidos}")
    print(f"  Fuegos apagados: {sum(a.apagarFuego for a in model.schedule)}")

    return history_models


