def ejecutar_simulacion_accion_por_accion(tipo_agente, max_steps=50, archivo_config='config.txt'):
    """
    Ejecuta simulación guardando UN FRAME POR CADA ACCIÓN de cada agente
    ¡ADVERTENCIA! Genera MUCHOS frames (puede ser lento)
    """
    model = Tablero(width=8, height=6, num_agentes=6,
                   tipo_agente=tipo_agente, archivo_config=archivo_config)

    history_models = []
    history_models.append(copy.deepcopy(model))

    print(f"🎬 Ejecutando simulación ACCIÓN POR ACCIÓN...")
    print(f"Agentes: {len(model.schedule)}")
    print(f"Civiles iniciales (POI): {len(model.posicionesPOI)}")
    print(f"⚠️  Esto generará MUCHOS frames (puede tardar)")

    for step in range(max_steps):
        if step % 5 == 0:
            print(f"  Step {step}... (frames: {len(history_models)})")

        # Procesar cada agente individualmente
        for agent_idx, agent in enumerate(model.schedule):
            # Resetear energía
            agent.energia_actual = agent.energia_maxima + agent.energia_guardada
            agent.energia_guardada = 0
            agent.celdas_exploradas.add(agent.pos)

            # Si está en base con civil, entregarlo
            if agent.pos in model.base_position and agent.tieneCivil:

                agent.tieneCivil = False
                model.civiles_rescatados += 1
                history_models.append(copy.deepcopy(model))

            # Ejecutar cada acción del agente
            acciones_realizadas = 0
            while agent.energia_actual > 0 and acciones_realizadas < 15:  # Límite de seguridad
                pos_antes = agent.pos
                energia_antes = agent.energia_actual
                fuego_antes = len(model.posicionesFuego)
                humo_antes = len(model.posicionesHumo)
                civil_antes = agent.tieneCivil
                pois_antes = len(model.posicionesPOI)

                # Ejecutar UNA acción según tipo de agente
                if type(agent).__name__ == 'BomberoAleatorio':
                    # Bombero aleatorio
                    accion = np.random.choice(['mover', 'puerta', 'fuego', 'humo', 'nada'],
                                             p=[0.5, 0.15, 0.15, 0.1, 0.1])

                    if accion == 'mover':
                        agent.movimiento_aleatorio()
                    elif accion == 'puerta':
                        vecinos = list(agent.get_neighbors())
                        if vecinos:
                            vecino = vecinos[np.random.randint(len(vecinos))]
                            if model.hay_puerta_entre(agent.pos, vecino):
                                agent.abrir_puerta(agent.pos, vecino)
                            else:
                                agent.gastar_energia()
                        else:
                            agent.gastar_energia()
                    elif accion == 'fuego':
                        if not agent.apagar_fuego():
                            agent.gastar_energia()
                    elif accion == 'humo':
                        if not agent.apagar_humo():
                            agent.gastar_energia()
                    else:
                        agent.gastar_energia()
                else:
                    # Bombero inteligente - ejecutar UNA acción
                    accion_realizada = False

                    # PRIORIDAD 1: Apagar fuego
                    if model.tieneFuegoEn(agent.pos):
                        accion_realizada = agent.apagar_fuego()
                        if accion_realizada:
                            history_models.append(copy.deepcopy(model))
                            acciones_realizadas += 1
                            continue

                    # PRIORIDAD 2: Apagar humo
                    if model.tieneHumoEn(agent.pos):
                        accion_realizada = agent.apagar_humo()
                        if accion_realizada:
                            history_models.append(copy.deepcopy(model))
                            acciones_realizadas += 1
                            continue

                   # PRIORIDAD 3: Si tiene civil, ir a base MÁS CERCANA
                    if agent.tieneCivil:
                        # CORRECCIÓN: usar "not in" para lista de bases
                        if agent.pos not in model.base_position:
                            # Encontrar la base más cercana
                            bases_con_distancia = []
                            for base in model.base_position:
                                camino = agent.buscar_camino_bfs(base)
                                if camino is not None:
                                    bases_con_distancia.append((base, len(camino)))

                            if bases_con_distancia:
                                base_mas_cercana = min(bases_con_distancia, key=lambda x: x[1])[0]
                                accion_realizada = agent.mover_hacia(base_mas_cercana)
                            else:
                                accion_realizada = agent.gastar_energia()
                        else:
                            # Ya está en base, entregar civil
                            agent.tieneCivil = False
                            model.civiles_rescatados += 1
                            accion_realizada = True
                            history_models.append(copy.deepcopy(model))
                            acciones_realizadas += 1
                            continue
                    else:
                        # PRIORIDAD 4: Buscar civil revelado
                        civil_objetivo = agent.encontrar_civil_revelado_mas_cercano()
                        if civil_objetivo:
                            accion_realizada = agent.mover_hacia(civil_objetivo)
                        else:
                            # PRIORIDAD 5: Buscar POI
                            poi_objetivo = agent.encontrar_poi_mas_cercano()
                            if poi_objetivo:
                                accion_realizada = agent.mover_hacia(poi_objetivo)
                            else:
                                # PRIORIDAD 6: Combatir fuego
                                fuego_objetivo = agent.encontrar_fuego_mas_cercano()
                                if fuego_objetivo:
                                    accion_realizada = agent.mover_hacia(fuego_objetivo)
                                else:
                                    accion_realizada = agent.movimiento_aleatorio()

                    if not accion_realizada:
                        agent.gastar_energia()

                # Si hubo cambio significativo, guardar frame
                cambio_significativo = (
                    agent.pos != pos_antes or
                    agent.energia_actual != energia_antes or
                    agent.tieneCivil != civil_antes or
                    len(model.posicionesFuego) != fuego_antes or
                    len(model.posicionesHumo) != humo_antes or
                    len(model.posicionesPOI) != pois_antes
                )

                if cambio_significativo:
                    history_models.append(copy.deepcopy(model))

                acciones_realizadas += 1

            # Guardar energía sobrante
            if agent.energia_actual > 0:
                agent.energia_guardada = min(agent.energia_actual, agent.energia_maxima)

            # Generar fuego después de cada agente
            fuegos_antes = len(model.posicionesFuego)
            model.generar_fuego()

            # Guardar frame si el fuego cambió
            if len(model.posicionesFuego) != fuegos_antes:
                history_models.append(copy.deepcopy(model))

        # Incrementar contador
        model.steps += 1
        model.datacollector.collect(model)

        # Verificar condiciones de término
        game_over, razon = model.verificar_game_over()
        if game_over:
            print(f"  ¡DERROTA! {razon} en step {step}")
            break

        if model.is_all_collected():
            print(f"  ¡VICTORIA! 7 civiles rescatados en step {step}")
            break

    # Frame final
    history_models.append(copy.deepcopy(model))

    print(f"\n✅ Simulación completada:")
    print(f"  Frames totales: {len(history_models)}")
    print(f"  Steps ejecutados: {model.steps}")
    print(f"  Civiles rescatados: {model.civiles_rescatados}")
    print(f"  Civiles perdidos: {model.civiles_perdidos}")
    print(f"  Fuegos apagados: {sum(a.apagarFuego for a in model.schedule)}")

    return history_models

