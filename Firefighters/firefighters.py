class BomberoAleatorio(Bombero):
    def step(self):
        self.energia_actual = self.energia_maxima + self.energia_guardada
        self.energia_guardada = 0

        # Entregar civil en base
        if self.pos in self.model.base_position and self.tieneCivil:
            self.tieneCivil = False
            self.model.civiles_rescatados += 1

        # Si está herido, regresar a base
        if self.herido:
            if self.pos in self.model.base_position:
                self.herido = False
                return
            else:
                base = self.base_mas_cercana()
                if base is not None:
                    while self.energia_actual > 0:
                        if not self.mover_hacia(base):
                            self.gastar_energia()
                        if self.pos in self.model.base_position:
                            break
                return

        while self.energia_actual > 0:
            # Usar np.random para probabilidades
            accion = np.random.choice(['mover', 'puerta', 'fuego', 'humo', 'nada'],
                                     p=[0.5, 0.15, 0.15, 0.1, 0.1])

            if accion == 'mover':
                self.movimiento_aleatorio()
            elif accion == 'puerta':
                vecinos = list(self.get_neighbors())
                if vecinos:
                    vecino = vecinos[np.random.randint(len(vecinos))]
                    if self.model.hay_puerta_entre(self.pos, vecino):
                        self.abrir_puerta(self.pos, vecino)
                    else:
                        self.gastar_energia()
                else:
                    self.gastar_energia()
            elif accion == 'fuego':
                if not self.apagar_fuego():
                    self.gastar_energia()
            elif accion == 'humo':
                if not self.apagar_humo():
                    self.gastar_energia()
            else:
                self.gastar_energia()

        if self.energia_actual > 0:
            self.energia_guardada = min(self.energia_actual, self.energia_maxima)

